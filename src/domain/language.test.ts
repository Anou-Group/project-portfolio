import { describe, expect, it } from "vitest";
import { lintText } from "./language";

const errors = (t: string) => lintText(t).filter((f) => f.severity === "error").map((f) => f.rule);
const warnings = (t: string) => lintText(t).filter((f) => f.severity === "warning").map((f) => f.rule);

describe("lintText — prohibited wording (examples from the reporting brief)", () => {
  it.each([
    ["Claude analysed the Shopify repository.", "ai-as-actor"],
    ["I helped Mahesh implement the enquiry forms.", "helping-someone"],
    ["The AI agent identified three issues.", "ai-as-actor"],
    ["Here are some recommendations for you.", "conversational"],
    ["As an AI language model, I cannot confirm this.", "ai-self-reference"],
    ["Report generated by Claude.", "by-ai"],
    ["Let me check the remaining tasks.", "conversational"],
    ["<thinking>maybe mark this done</thinking>", "internal-commentary"],
    ["TODO: confirm the date", "internal-commentary"],
    ["🤖 Generated with Claude Code", "tool-footer"],
    ["ChatGPT wrote the copy for the About page.", "ai-as-actor"],
  ])("rejects %j", (text, rule) => {
    expect(errors(text)).toContain(rule);
  });
});

describe("lintText — legitimate content", () => {
  it.each([
    "Reviewed the Shopify repository and identified outstanding development requirements.",
    "Implemented enquiry forms covering retail, wholesale and supply-contract enquiries.",
    "Three outstanding issues were identified during testing.",
    "Recommended next steps.",
    "The 'ask' box is not built: it needs an Anthropic API key.",
    "Evaluated AI-assisted product description tools for the catalogue.",
    "Automation sends the weekly summary email every Monday.",
    "Hired a retail assistant for the store.",
  ])("does not reject %j", (text) => {
    expect(errors(text)).toEqual([]);
  });

  it("flags legitimate AI mentions as warnings for a human to read, not errors", () => {
    expect(warnings("The 'ask' box needs an Anthropic API key.")).toContain("ai-mention");
    expect(warnings("Evaluated AI-assisted product description tools.")).toContain("ai-mention");
  });

  it("flags placeholders and strong claims as warnings", () => {
    expect(warnings("Go-live date TBC.")).toContain("placeholder-unknown");
    expect(warnings("The store is fully tested and production-ready.")).toContain("unverified-claim");
  });

  it("does not flag ordinary words that contain 'ai'", () => {
    expect(lintText("Maintain the email campaign and retail pricing.")).toEqual([]);
  });
});
